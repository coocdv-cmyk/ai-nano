"""H5 — Programming intelligence: repair buggy AST programs."""

from __future__ import annotations

import time
from typing import Any

from .ast_engine import (
    SEEN_TEMPLATES,
    UNSEEN_TEMPLATES,
    AstError,
    exhaustive_bounded_diff,
    evaluate_ast,
    buggy_from_template,
    repair_program,
    sample_inputs,
    template_args,
    template_correct,
)
from .config import probe_hardware
from .metrics import mean_ci

LEVELS = {
    # level: (templates, bug count, support k)
    "L1": (SEEN_TEMPLATES, 1, 4),
    "L2": (SEEN_TEMPLATES, 2, 4),
    "L3": (SEEN_TEMPLATES, 1, 2),   # hidden transformation, minimal evidence
    "L4": (UNSEEN_TEMPLATES, 1, 4),  # previously unseen AST structures
    "L5": (SEEN_TEMPLATES + UNSEEN_TEMPLATES, 3, 6),  # multi-step repair
}


def _domain(name: str):
    args = template_args(name)
    if name in ("sum_range",):
        return [dict(zip(args, (a, b))) for a in range(0, 9) for b in range(a, min(a + 11, 12))]
    if name == "sum_squares":
        return [dict(n=v) for v in range(0, 15)]
    if name == "pow2":
        return [dict(n=v) for v in range(0, 15)]
    if name == "sum_mult":
        return [dict(zip(args, (n, m))) for n in range(0, 11) for m in range(0, 6)]
    if name == "sum_gcd":
        return [dict(zip(args, (a, b))) for a in range(1, 11) for b in range(1, 11)]
    if name == "clamp":
        return [dict(zip(args, (x, lo, hi)))
                for x in range(-2, 12) for lo in (0, 3) for hi in (4, 8) if lo <= hi]
    raise ValueError(name)





def run_h5(cfg, *, seeds=None, n_test: int = 6,
           max_candidates: int = 4000) -> dict[str, Any]:
    seeds = tuple(seeds or cfg.seeds[:8])
    t0 = time.perf_counter()
    rows: list[dict[str, Any]] = []
    for level, (templates, n_bugs, k) in LEVELS.items():
        for seed in seeds:
            for template in templates:
                import random as _random
                rng = _random.Random(f"h5:{level}:{template}:{seed}")
                correct = template_correct(template)
                inputs = sample_inputs(template, rng, k + 1 + n_test, lo=0, hi=16)
                buggy = buggy_from_template(template, rng, n_bugs,
                                            check_envs=inputs[:k + 1])
                if buggy is None:
                    rows.append({
                        "level": level, "template": template, "seed": seed,
                        "n_bugs": n_bugs, "k": k,
                        "repair_found": False, "reason": "nonterminating-bug-instance",
                        "failure_category": "execution-error",
                        "candidates_tried": 0, "semantically_correct": None,
                        "false_repair": False,
                        "heldout_behavioral_correct": None,
                    })
                    continue

                # The repair search receives examples generated by the
                # hidden correct specification (not the buggy program's
                # outputs), mirroring the directive's "hidden transformation
                # rules with a small number of input/output examples".
                def out(stmts, env):
                    try:
                        return evaluate_ast(stmts, env)
                    except AstError:
                        return None

                train_envs = inputs[:k]
                val_env = inputs[k]
                test_envs = inputs[k + 1:k + 1 + n_test]
                support = [(e, out(correct, e)) for e in train_envs] + \
                          [(val_env, out(correct, val_env))]
                heldout = [(env, out(correct, env)) for env in test_envs]

                # NOTE: the repair search receives ONLY the example outputs —
                # never the oracle.  Verification against the hidden correct
                # program is an evaluation-side check applied afterwards.
                repair, n_tried, reason = repair_program(
                    buggy, support, verify=None,
                    max_width=3 if level == "L5" else 2,
                    max_candidates=max_candidates)
                semantic_ok = None
                matches_examples = None
                if repair is not None:
                    matches_examples = all(
                        _try(repair, e) == exp for e, exp in support)
                    try:
                        semantic_ok = exhaustive_bounded_diff(
                            repair, correct, _domain(template))
                    except AstError:
                        semantic_ok = False
                false_repair = bool(repair is not None and semantic_ok is False)
                if repair is not None and semantic_ok is True:
                    failure_category = "success"
                elif repair is not None:
                    failure_category = "overgeneralization"
                elif reason in ("budget-exhausted", "candidate-cap-exhausted"):
                    failure_category = "search-explosion"
                else:
                    failure_category = "search-explosion"
                rows.append({
                    "level": level,
                    "template": template,
                    "seed": seed,
                    "n_bugs": n_bugs,
                    "k": k,
                    "failure_category": failure_category,
                    "repair_found": repair is not None,
                    "reason": reason,
                    "candidates_tried": n_tried,
                    "semantically_correct": semantic_ok,
                    "false_repair": false_repair,
                    "heldout_behavioral_correct": (
                        None if repair is None else
                        sum(1 for env, exp in heldout if _try(repair, env) == exp)
                        / len(heldout)),
                })
    summary = {}
    for level in LEVELS:
        sel = [r for r in rows if r["level"] == level]
        summary[level] = {
            "n": len(sel),
            "repair_rate": _mean(r["repair_found"] for r in sel),
            "semantic_correct_rate": _mean(
                r["semantically_correct"] is True for r in sel),
            "false_repair_rate": _mean(r["false_repair"] for r in sel),
            "holdout_behavioral_mean": mean_ci(
                r["heldout_behavioral_correct"] for r in sel
                if r["heldout_behavioral_correct"] is not None),
            "candidates_median": _median(r["candidates_tried"] for r in sel),
        }
    return {
        "experiment_id": "H5",
        "experiment_name": "Programming Intelligence and AST Transformation",
        "status": "completed",
        "held_out_templates_unseen_in_repair": list(UNSEEN_TEMPLATES),
        "levels": list(LEVELS),
        "episodes": rows,
        "summary": summary,
        "hardware": probe_hardware().as_dict(),
        "wall_s": time.perf_counter() - t0,
    }


def _try(cand, env):
    try:
        return evaluate_ast(cand, env, max_steps=2000)
    except AstError:
        return None


def _mean(xs) -> float | None:
    xs = list(xs)
    return round(sum(xs) / len(xs), 6) if xs else None


def _median(xs):
    xs = sorted(xs)
    n = len(xs)
    if n == 0:
        return None
    mid = n // 2
    return xs[mid] if n % 2 else (xs[mid - 1] + xs[mid]) / 2
